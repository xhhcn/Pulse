/* Flags, OS logos and CPU logos.

   These used to come from api.iconify.design at runtime as
   `prefix:name.svg`. Iconify stopped serving that form (it answers 404;
   only `prefix/name.svg` works), which blanked every flag and logo, and
   each icon was a third-party round trip (0.4-1 s from mainland China).
   The icons the dashboard shows are now shipped with it under
   /icons/<prefix>/<name>.svg (public/icons, regenerated by
   scripts/sync-icons.mjs). Anything else — the few flags too large to
   ship, or an os_icon a future agent reports — still comes from the
   Iconify API, in the form it serves today. */
import { FLAG_ICONS, LOCAL_ICONS } from './icon-manifest.ts';

/* Icon names must be a plain iconify "prefix:name" pair before they can
   shape a URL: agent-reported names (os_icon) must not be able to steer
   the request at another path ("/", "..", "?", "#" are all rejected). */
export const ICONIFY_NAME_RE = /^[a-z0-9-]+:[a-z0-9-]+$/i;

/* Agent icons that do not work at icon size, and what is drawn instead.
   devicon:oracle (Oracle Linux) is the "ORACLE" wordmark, which comes out
   26 x 4 px; Oracle's ring mark reads at that size. */
const DISPLAY_ALIASES: Readonly<Record<string, string>> = {
  'devicon:oracle': 'simple-icons:oracle',
};

/** URL of an icon's SVG, or null for a name that is not a plain prefix:name pair. */
export function iconSvgUrl(name: string, height: number): string | null {
  let full = String(name || '');
  if (!ICONIFY_NAME_RE.test(full)) return null;
  full = DISPLAY_ALIASES[full] || full;
  const [prefix, icon] = full.split(':');
  if (LOCAL_ICONS.has(full)) return `/icons/${prefix}/${icon}.svg`;
  return `https://api.iconify.design/${prefix}/${icon}.svg?height=${height}`;
}

const FLAG_NAMES: ReadonlySet<string> = new Set(Object.values(FLAG_ICONS));

/** Emoji One (v1) flag icon for a flag name such as "hong-kong-sar-china", if the set has one. */
export function flagIconForSlug(slug: string): string | null {
  const name = `flag-for-${String(slug || '')}`;
  return FLAG_NAMES.has(name) ? `emojione-v1:${name}` : null;
}

/** Emoji One (v1) flag icon for an ISO 3166-1 alpha-2 code ("UK" counts as GB), or null. */
export function flagIconForCode(code: string): string | null {
  const c = String(code || '').trim().toUpperCase();
  const name = FLAG_ICONS[c === 'UK' ? 'GB' : c];
  return name ? `emojione-v1:${name}` : null;
}
